// Quellen der Koordinaten (selenografisch, planetozentrisch, Ost positiv, −180…180):
// - Natürliche Objekte: IAU/USGS Gazetteer of Planetary Nomenclature
//   (https://planetarynames.wr.usgs.gov, Shapefile MOON_nomenclature_center_pts, abgerufen 2026-10-22),
//   Mittelpunkt und Durchmesser (bei Tälern/Rillen/Gebirgen: Länge bzw. Ausdehnung) auf 0,01° bzw. 1 km gerundet.
//   Ausnahme: Das Südpol-Aitken-Becken ist kein IAU-benanntes Objekt; Mittelpunkt (53° S, 191° O) und
//   Größe (2400 × 2050 km) nach Garrick-Bethell & Zuber (2009), Icarus 204, 399–408.
// - Landeplätze: LROC-Tabelle der menschengemachten Objekte (Wagner et al. 2017, Icarus 283, 92–103;
//   fortgeschrieben, Stand 2026-08-14), bei Apollo die Position der Mondfähre.
//   Luna 2, Luna 9 und Luna 13 sind in LRO-Bildern nicht sicher gefunden – dort gelten die
//   Angaben des NASA Space Science Data Coordinated Archive (NSSDCA).
// - Missionsdaten (Datum = Landung bzw. Einschlag in UTC): NASA NSSDCA bzw. die jeweilige Raumfahrtagentur.
//
// Alle Beschreibungstexte sind eigene Formulierungen.

export type MoonFeatureType = 'mare' | 'crater' | 'mons' | 'vallis' | 'rima' | 'landing' | 'other';

export interface MoonFeature {
  id: string;
  /** IAU-Name, z. B. 'Copernicus', 'Mare Imbrium' */
  name: string;
  /** Gebräuchlicher deutscher Name, falls es einen gibt (z. B. 'Meer der Ruhe') */
  de?: string;
  type: MoonFeatureType;
  /** Selenografisch, Grad, Ost positiv, −180…180 */
  lat: number;
  lon: number;
  /** Durchmesser bzw. Länge in km */
  diameter?: number;
  /** Wie gut sichtbar: 1 = bloßes Auge, 2 = Fernglas, 3 = kleines Teleskop, 4 = nur Raumsonden (Rückseite) */
  visibility: 1 | 2 | 3 | 4;
  info: { de: string; en: string };
  /** Nur bei Landeplätzen */
  mission?: { date: string; agency: string; crewed: boolean };
}

